"""Compose <workspace>\\AI_Music\\logs\\setup_report.txt from the run reports.

<workspace> = G:\\AIMUSIC (all paths are resolved from this
file's location, so the project folder can be moved without editing the script).

Reads logs/model_load_report.json + logs/generate_report.json (written by
test_model_load.py / generate_test.py) and the live environment, then writes a
single human-readable summary.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

from _common import human, safe_stdio

# <workspace>\AI_Music\scripts\write_setup_report.py -> <workspace>\AI_Music
BASE_DIR = Path(__file__).resolve().parents[1]
MODELS_DIR = BASE_DIR / "models" / "Ace-Step1.5"
LOG_DIR = BASE_DIR / "logs"
TARGET_WAV = BASE_DIR / "generated" / "test_lofi_01.wav"
REPORT_PATH = LOG_DIR / "setup_report.txt"




def read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def dir_stats(path: Path) -> tuple[int, float]:
    files = [p for p in path.rglob("*") if p.is_file() and p.parent.name != ".cache"]
    return len(files), float(sum(p.stat().st_size for p in files))


WEIGHTS = (
    "acestep-v15-turbo/model.safetensors",
    "acestep-5Hz-lm-1.7B/model.safetensors",
    "Qwen3-Embedding-0.6B/model.safetensors",
    "vae/diffusion_pytorch_model.safetensors",
)


def sha_status(verified: dict) -> str:
    ok = 0
    for rel in WEIGHTS:
        path = MODELS_DIR / rel
        entry = verified.get(rel) if isinstance(verified, dict) else None
        if not path.is_file() or not isinstance(entry, dict):
            continue
        stat = path.stat()
        if (int(entry.get("size", -1)) == int(stat.st_size)
                and int(entry.get("mtime", -1)) == int(stat.st_mtime)
                and entry.get("sha256")):
            ok += 1
    if ok == len(WEIGHTS):
        return f"已驗證 ({ok}/{len(WEIGHTS)})"
    if ok:
        return f"部分驗證 ({ok}/{len(WEIGHTS)})"
    return "未驗證"


def main() -> int:
    safe_stdio()
    load = read_json(LOG_DIR / "model_load_report.json")
    gen = read_json(LOG_DIR / "generate_report.json")
    runtime = load.get("runtime", {})
    plan = load.get("plan", {})
    audio = gen.get("audio", {})
    verified = read_json(MODELS_DIR / ".verified.json").get("files", {})
    weights_sha = sha_status(verified)
    gpu_title = runtime.get("gpu_name") or "GPU"

    files, total = dir_stats(MODELS_DIR)
    lines: list[str] = []
    add = lines.append

    add("ACE-Step 1.5 — local offline setup report")
    add("=" * 68)
    add(f"generated by : {Path(__file__).name}")
    add("")
    add("[1] Model location and size")
    add(f"  model dir        : {MODELS_DIR}")
    add(f"  DiT model        : acestep-v15-turbo (official ACE-Step/Ace-Step1.5)")
    add(f"  LM model         : acestep-5Hz-lm-1.7B (official)")
    add(f"  text encoder     : Qwen3-Embedding-0.6B (official)")
    add(f"  VAE              : acestep VAE (official)")
    add(f"  files on disk    : {files}")
    add(f"  total size       : {human(total)}")
    add(f"  source           : huggingface.co/ACE-Step/Ace-Step1.5 (official, {weights_sha})")
    add("")
    add("[2] Python / PyTorch / CUDA")
    add(f"  python           : {runtime.get('python', sys.version.split()[0])}")
    add(f"  python exe       : {sys.executable}")
    add(f"  torch            : {runtime.get('torch', 'n/a')}")
    add(f"  torch CUDA build : {runtime.get('torch_cuda', 'n/a')}")
    add(f"  cuda available   : {runtime.get('cuda_available', 'n/a')}")
    add("")
    add(f"[3] {gpu_title} status")
    add(f"  gpu              : {runtime.get('gpu_name', 'n/a')}")
    add(f"  compute cap.     : {runtime.get('compute_capability', 'n/a')}")
    add(f"  total VRAM       : {runtime.get('total_vram_gb', 'n/a')} GB")
    add(f"  free VRAM at start: {runtime.get('free_vram_gb', 'n/a')} GB")
    add(f"  bf16 supported   : {runtime.get('bf16_supported', 'n/a')}")
    add(f"  gpu tier (auto)  : {plan.get('tier', 'n/a')} / max duration with LM "
        f"{plan.get('max_duration_with_lm', 'n/a')} s")
    add(f"  peak VRAM (load) : {load.get('peak_vram_gb', 'n/a')} GB "
        f"(reserved {load.get('reserved_vram_gb', 'n/a')} GB)")
    add("")
    add("[4] Model load test (test_model_load.py)")
    add(f"  result           : {'SUCCESS' if load.get('ok') else 'FAILED / not run'}")
    add(f"  blocking step    : {load.get('stage', 'n/a')}")
    add(f"  DiT load         : {load.get('dit_seconds', 'n/a')} s — {load.get('dit_message', '')}")
    add(f"  DiT params       : {load.get('dit_params_b', 'n/a')} B")
    add(f"  LM load          : {load.get('lm_seconds', 'n/a')} s — {load.get('lm_message', '')}")
    add(f"  sample rate      : {load.get('sample_rate', 'n/a')} Hz")
    if load.get("errors"):
        add(f"  errors           : {load['errors']}")
    add("")
    add("[5] Music generation test (generate_test.py)")
    add(f"  result           : {'SUCCESS' if gen.get('ok') else 'FAILED / not run'}")
    add(f"  blocking step    : {gen.get('stage', 'n/a')}")
    add(f"  generation time  : {gen.get('generate_seconds', 'n/a')} s")
    add(f"  prompt           : Lo-fi chill instrumental, 78 BPM, 180 s, WAV")
    add(f"  output wav       : {TARGET_WAV}")
    if TARGET_WAV.is_file():
        add(f"  wav exists       : yes ({human(float(TARGET_WAV.stat().st_size))})")
    else:
        add("  wav exists       : no")
    if audio:
        add(f"  wav properties   : {audio.get('sample_rate')} Hz, {audio.get('channels')} ch, "
            f"{audio.get('duration_sec')} s, peak {audio.get('peak')}, rms {audio.get('rms')}")
    if gen.get("errors"):
        add(f"  errors           : {gen['errors']}")
    add("")
    add("[6] Runtime mode")
    add("  offline          : HF_HUB_OFFLINE=1, TRANSFORMERS_OFFLINE=1")
    add(f"  checkpoints env  : ACESTEP_CHECKPOINTS_DIR={MODELS_DIR}")
    add("  webui / api srv  : NOT used (no gradio, no fastapi, no localhost server)")
    add("  device policy    : CUDA (RTX 3060), CPU offload for VAE/text encoder, LM backend='pt'")
    add("")

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"[report] written to {REPORT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
